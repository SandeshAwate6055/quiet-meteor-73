"""Prepare one revised challenge smoke; preserve all historical inputs/results.

Uses the existing request exporter and handoff packager with a deliberately empty
reference store. Two NEW single-view candidates must be reviewed before the scene.
No models are imported or images generated by this script.
"""
import argparse
import json
from pathlib import Path
import tempfile

from src.asset_store import AssetStore
from src.assets import export_request
from src.batch_handoff import create_handoff
from src.characters import load_bible, REFERENCE_SPEC_REVISION
from src.schema import load_story
from src.production_state import file_hash, write_json

ROOT = Path(__file__).resolve().parents[1]


def prepare(destination, name="challenge_smoke_v2"):
    destination = Path(destination).resolve()
    destination.mkdir(parents=True, exist_ok=True)
    story = load_story(ROOT / "scripts/tortoise_and_hare.json")
    bible = load_bible(ROOT / "configs/character_bible.json")
    with tempfile.TemporaryDirectory(prefix="smoke_request_") as temp:
        directory = Path(temp)
        store = AssetStore(directory / "empty_references")
        request_path = directory / "request.json"
        export_request(store, story, bible, request_path, ["challenge"])
        request = json.loads(request_path.read_text(encoding="utf-8"))
        request["generation_policy"] = {"allowed_scene_ids": ["challenge"], "full_batch_enabled": False,
            "require_reference_review": True, "reference_spec_revision": REFERENCE_SPEC_REVISION}
        request["quality_review"] = {"previous_smoke": "failed_human_visual_review", "approved": False}
        write_json(request_path, request)
        package_path = directory / "package.zip"
        metadata = create_handoff(request_path, store, package_path)
        for source, target in ((request_path, destination / f"{name}.json"), (package_path, destination / f"{name}.zip")):
            if target.exists():
                if file_hash(target) != file_hash(source):
                    raise ValueError(f"Existing artifact differs: {target}. Choose a NEW --name; nothing was overwritten.")
            else:
                with target.open("xb") as stream:
                    stream.write(source.read_bytes())
    return {**metadata, "package_path": str(destination / f"{name}.zip"), "request_path": str(destination / f"{name}.json"),
            "scene_ids": ["challenge"], "new_references_required": ["hare", "tortoise"],
            "historical_references_unchanged": True, "generation_started": False}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=ROOT / "examples")
    parser.add_argument("--name", default="challenge_smoke_v2")
    args = parser.parse_args()
    if not args.name.replace("_", "").replace("-", "").isalnum():
        parser.error("Use a simple file name")
    print(json.dumps(prepare(args.output_dir, args.name), indent=2))
